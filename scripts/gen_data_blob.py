#!/usr/bin/env python3
"""dump_state.py's <out>.<lib>.cand.bin -> C include for gotfix.cpp (DATA_INC).
   python3 scripts/gen_data_blob.py --blob state.libil2cpp.so.cand.bin --lib libil2cpp.so --out scripts/gotfix/data_libil2cpp.inc
Keeps only the non-GOT candidates (file value != the raw .plt value; GOT slots are handled by the got table).
They must form ONE contiguous 8-byte-stride run and every live value must fit in 32 bits, else it refuses."""
import argparse, struct, zlib, sys
ap = argparse.ArgumentParser()
ap.add_argument("--blob", required=True); ap.add_argument("--lib", required=True); ap.add_argument("--out", required=True)
ap.add_argument("--plt0", default="0x174eac00", help="raw .plt value of GOT slots to ignore")
ap.add_argument("--sparse", action="store_true", help="scattered words (64-bit values, kept only if the on-disk value looks random: top 16 bits != 0)")
a = ap.parse_args(); plt0 = int(a.plt0, 16)
d = zlib.decompress(open(a.blob, "rb").read())
recs = [struct.unpack_from("<QQQ", d, i) for i in range(0, len(d), 24)]
if a.sparse:
    sp = sorted((v, f, l) for v, l, f in recs if f != plt0 and (f >> 48))
    if not sp: sys.exit("no scrambled words")
    with open(a.out, "w") as f:
        f.write(f"// generated by gen_data_blob.py --sparse. {len(sp)} scrambled words for {a.lib}: {{va, on-disk value, plaintext}}\n")
        f.write("#define HAVE_SPARSE 1\nstruct SparseW { uint64_t va, from, to; };\n")
        f.write(f"static const uint32_t kSparseN = {len(sp)};\nstatic const SparseW kSparse[] = {{\n")
        for v, ff, l in sp: f.write(f"  {{{hex(v)}ULL,{hex(ff)}ULL,{hex(l)}ULL}},\n")
        f.write("};\n")
    print(f"{a.out}: {len(sp)} sparse words ({sum(1 for x in sp if x[2]==0)} decode to 0) from {hex(sp[0][0])} to {hex(sp[-1][0])}")
    sys.exit(0)
data = sorted((v, l) for v, l, f in recs if f != plt0)
if not data: sys.exit("no data candidates")
for (v0, _), (v1, _) in zip(data, data[1:]):
    if v1 - v0 != 8: sys.exit(f"not contiguous: {hex(v0)} -> {hex(v1)}")
if any(l >> 32 for _, l in data): sys.exit("a live value does not fit in 32 bits")
vals = [l for _, l in data]
with open(a.out, "w") as f:
    f.write(f"// generated by gen_data_blob.py from a stock process dump. {len(vals)} descrambled words for {a.lib}\n")
    f.write(f"static const uint64_t kDataVa = {hex(data[0][0])}ULL;\nstatic const uint32_t kDataN = {len(vals)};\nstatic const uint32_t kData[] = {{\n")
    for i in range(0, len(vals), 8): f.write("  " + ",".join(f"0x{x:x}" for x in vals[i:i+8]) + ",\n")
    f.write("};\n")
print(f"{a.out}: {len(vals)} words from {hex(data[0][0])} to {hex(data[-1][0])}")
