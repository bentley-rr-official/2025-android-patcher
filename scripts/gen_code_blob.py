#!/usr/bin/env python3
"""dump_extra.py's <out>.text.<lib>.runs.bin  ->  C include for gotfix.cpp (CODE_INC).
   python3 scripts/gen_code_blob.py --runs extra_late.text.libwebrtc.so.runs.bin --so <ORIGINAL libwebrtc.so> \
           --lib libwebrtc.so --out scripts/gotfix/code_libwebrtc.inc
PairIP stores some code encrypted on disk and its native program decrypts it at startup. The re-signed app has no such
program, so the first call into that code dies with SIGILL. This writes the decrypted bytes (dumped from a STOCK process)
back before the lib's constructors run. Each run carries an FNV-1a hash of its on-disk bytes and of the plaintext, so the
runtime only patches when the live bytes are still exactly the on-disk ones."""
import argparse, struct, sys, zlib
ap = argparse.ArgumentParser()
ap.add_argument("--runs", required=True); ap.add_argument("--so", required=True)
ap.add_argument("--lib", required=True); ap.add_argument("--out", required=True)
ap.add_argument("--min-len", type=int, default=1024, help="skip runs shorter than this (tiny runs are runtime data, not code)")
ap.add_argument("--allow-segment", default="", help="comma list of hex vaddr starts of exec segments to accept (default: only the first/main one)")
a = ap.parse_args()

def fnv(b):
    h = 0xcbf29ce484222325
    for x in b: h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h

raw = open(a.so, "rb").read()
phoff, = struct.unpack_from("<Q", raw, 0x20); phes, phn = struct.unpack_from("<HH", raw, 0x36)
segs = []
for i in range(phn):
    ty, fl, off, va, pa, fsz, msz, al = struct.unpack_from("<IIQQQQQQ", raw, phoff + i * phes)
    if ty == 1 and fl & 1: segs.append((va, off, fsz))
if not segs: sys.exit("no executable PT_LOAD")
ok = {segs[0][0]} | {int(x, 16) for x in a.allow_segment.split(",") if x}
d = zlib.decompress(open(a.runs, "rb").read()); i = 0; runs = []
while i < len(d):
    v, n = struct.unpack_from("<QI", d, i); runs.append((v, d[i + 12:i + 12 + n])); i += 12 + n
keep = []
for v, live in runs:
    seg = next((s for s in segs if s[0] <= v < s[0] + s[2]), None)
    if seg is None or v + len(live) > seg[0] + seg[2]: sys.exit(f"run {hex(v)} not inside an exec segment")
    if len(live) < a.min_len or seg[0] not in ok or v % 4 or len(live) % 4:
        print(f"skip run {hex(v)} len {len(live)} (segment {hex(seg[0])})"); continue
    fo = seg[1] + v - seg[0]; disk = raw[fo:fo + len(live)]
    if disk == live: sys.exit(f"run {hex(v)} identical to disk?")
    keep.append((v, disk, live))
if not keep: sys.exit("nothing to write")
words = []; meta = []
for v, disk, live in keep:
    meta.append((v, len(live) // 4, len(words), fnv(disk), fnv(live)))
    words += struct.unpack("<%dI" % (len(live) // 4), live)
with open(a.out, "w") as f:
    f.write(f"// generated by gen_code_blob.py: decrypted code for {a.lib} ({len(keep)} run(s), {len(words)} words). Keep out of git.\n")
    f.write("#define HAVE_CODE 1\nstruct CodeRun { uint64_t va; uint32_t nwords, off; uint64_t h_disk, h_plain; };\n")
    f.write(f"static const uint32_t kCodeRunsN = {len(meta)};\nstatic const CodeRun kCodeRuns[] = {{\n")
    for v, n, o, hd, hp in meta: f.write(f"  {{{hex(v)}ULL,{n},{o},{hex(hd)}ULL,{hex(hp)}ULL}},\n")
    f.write(f"}};\nstatic const uint32_t kCode[{len(words)}] = {{\n")
    for k in range(0, len(words), 8): f.write("  " + ",".join(f"0x{x:08x}" for x in words[k:k + 8]) + ",\n")
    f.write("};\n")
print(f"{a.out}: {len(keep)} run(s), {len(words)} words ({len(words)*4} bytes); first {hex(keep[0][0])}")
